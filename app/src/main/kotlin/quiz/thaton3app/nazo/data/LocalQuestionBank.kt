    /**
     * Returns up to [count] questions, optionally filtered by a free-text [topic]
     * (matched against anime / theme / text). Results are shuffled so repeated
     * quizzes differ. Mirrors how the future API will honour topic + count.
     */
    fun getQuestions(count: Int, topic: String = ""): List<Question> {
        val base = if (topic.isBlank()) {
            allQuestions
        } else {
            val filtered = allQuestions.filter { it.matches(topic) }
            if (filtered.isEmpty()) allQuestions else filtered
        }
        val pool = if (base.size >= count) base else (base + allQuestions).distinctBy { it.text }
        return pool.shuffled().take(count)
    }

    private fun Question.matches(topic: String): Boolean {
        val t = topic.trim()
        if (t.isEmpty()) return true
        return anime.contains(t, ignoreCase = true) ||
            theme.contains(t, ignoreCase = true) ||
            text.contains(t, ignoreCase = true)
    }
